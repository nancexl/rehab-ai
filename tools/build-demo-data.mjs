// Builds dist/cases/demo.json for the offline judge demo from the recorded evidence (no network, no keys).
import { readFileSync, writeFileSync } from 'node:fs';
const ev = p => JSON.parse(readFileSync(new URL('../evidence/live/' + p, import.meta.url), 'utf8'));
const v1 = ev('pipeline-case1-liner/agent-v1.json'), rec1 = ev('pipeline-case1-liner/build-record.json'), rec3 = ev('pipeline-case3-coupon/build-record.json');
const cases = JSON.parse(readFileSync(new URL('../dist/cases/cases.json', import.meta.url), 'utf8')).cases;
const trace = [];
for (const t of v1.trace) {
  if (t.type === 'model' && t.tool_calls?.length) trace.push(['model', `Nemotron → ${t.tool_calls.map(c => c.name).join(', ')}`, `${t.latency_ms} ms · ${t.usage.total_tokens} tokens`]);
  else if (t.type === 'model') trace.push(['say', 'Nemotron says', t.text]);
  else if (t.type === 'tool') trace.push(['tool', `${t.name} (code)`, t.result && t.result.ok === false ? 'failed' : (t.result?.status || 'ok')]);
}
const check = rec1.steps.find(s => s.step === 'check');
const newton = rec3.steps.find(s => s.step === 'check').newton;
const out = {
  source: 'evidence/live/pipeline-case1-liner/agent-v1.json + build-record.json; evidence/live/pipeline-case3-coupon/build-record.json',
  run: { timestamp: v1.timestamp, provider: v1.provider, model: v1.model_returned, fell_back: v1.fell_back, totals: v1.totals, claim_audit: v1.claim_audit },
  girths_mm: cases[0].girths_mm, trace,
  checks: check.checks.map(c => [c.id.replace(/_/g, ' '), c.ok]),
  outcome: { cut_lengths_mm: v1.outcome.cut_lengths_mm, spec_sha256: v1.outcome.spec_sha256, foam_thickness_mm: v1.outcome.options.foam_thickness_mm, tiles: 5 },
  pattern_outline: cases[0].pattern_outline,
  profile: cases[0].profile.map(p => [p.z, p.girth_mm]),
  newton: { recorded: newton.recorded, engine: newton.engine, mesh: newton.mesh, cases: newton.cases },
};
writeFileSync(new URL('../dist/cases/demo.json', import.meta.url), JSON.stringify(out));
// Same data as a script so the demo also runs from file:// with no fetch.
writeFileSync(new URL('../dist/demo-data.js', import.meta.url), '// Generated by tools/build-demo-data.mjs from recorded evidence.\nwindow.DEMO_DATA = ' + JSON.stringify(out) + ';\n');
console.log('demo.json', trace.length, 'trace rows', out.checks.length, 'checks', out.newton.cases.length, 'newton runs');
